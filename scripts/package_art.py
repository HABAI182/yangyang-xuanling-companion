"""Mechanical PNG slicing, scaling and editable PSD packaging. No AI repainting.
Artwork itself is generated by the built-in imagegen tool; these are draft layers.
"""
from pathlib import Path
import json, os, sys
from PIL import Image
if os.environ.get('PET_PSD_TOOLS'):sys.path.insert(0,os.environ['PET_PSD_TOOLS'])
from psd_tools import PSDImage

ROOT = Path(__file__).resolve().parents[1]
ASSETS = ROOT / 'public/assets'
SRC = ROOT / 'art/source'
WIDTH, HEIGHT = 1400, 1360
sheet = Image.open(SRC / 'devices-v1.png').convert('RGBA')
head = Image.open(SRC / 'head-underpaint-v1.png').convert('RGBA')
if sheet.size != (1254,1254) or head.size != (1254,1254):
    raise ValueError('Candidate dimensions changed; re-observe before slicing')

sources = {
    'head-body': head,
    'keyboard': sheet.crop((0, 180, 682, 475)),
    'mouse-hand': sheet.crop((700, 160, 1254, 550)),
    'keyboard-hand': sheet.crop((120, 865, 666, 1120)),
    'bird': sheet.crop((650, 660, 1254, 1220)),
}
placements = {
    'head-body': (0,0,1220), 'keyboard': (265,1010,1100),
    'mouse-hand': (95,930,290), 'keyboard-hand': (765,956,235),
    'bird': (1130,890,235),
}
layers=[]
for name,img in sources.items():
    # Ignore near-zero antialias noise only when calculating trim bounds.
    # Preserve the original alpha in the actual packaged image.
    box=img.getchannel('A').point(lambda a:255 if a>32 else 0).getbbox()
    if not box: raise ValueError(f'Empty {name}')
    img=img.crop(box)
    img.save(ASSETS / f'{name}-v1.png')
    x,y,w=placements[name];h=round(img.height*w/img.width)
    img=img.resize((w,h),Image.Resampling.LANCZOS)
    if x+w>WIDTH or y+h>HEIGHT: raise ValueError(f'Out-of-canvas {name}: {x,y,w,h}')
    layers.append((name,img,x,y))
layout={'schema':1,'draft':True,'canvas':{'width':WIDTH,'height':HEIGHT},'layers':[{'id':n,'file':f'/assets/{n}-v1.png','x':x,'y':y,'width':im.width,'height':im.height} for n,im,x,y in layers]}
(ASSETS/'layers.json').write_text(json.dumps(layout,indent=2)+'\n',encoding='utf-8')
merged=Image.new('RGBA',(WIDTH,HEIGHT))
for _,im,x,y in layers: merged.alpha_composite(im,(x,y))
merged.save(SRC/'composition-v1.png')

psd=PSDImage.new(mode='RGB',size=(WIDTH,HEIGHT),depth=8)
for name,img,x,y in layers:psd.create_pixel_layer(img,name=name,top=y,left=x)
psd.save(SRC/'YangyangXuanling-Layers-v1.psd')
reread=PSDImage.open(SRC/'YangyangXuanling-Layers-v1.psd')
if len(reread)!=len(layers):raise ValueError('PSD layer count mismatch')
for layer,(name,img,x,y) in zip(reread,layers):
    if layer.name!=name or layer.left!=x or layer.top!=y:raise ValueError('PSD layer metadata mismatch')
icon=merged.copy();icon.thumbnail((256,256),Image.Resampling.LANCZOS)
square=Image.new('RGBA',(256,256));square.alpha_composite(icon,((256-icon.width)//2,(256-icon.height)//2))
square.save(ROOT/'src-tauri/icons/icon.ico',sizes=[(16,16),(32,32),(48,48),(64,64),(128,128),(256,256)])
print(json.dumps({'layers':len(layers),'canvas':[WIDTH,HEIGHT],'psdBytes':(SRC/'YangyangXuanling-Layers-v1.psd').stat().st_size,'placements':layout['layers']},ensure_ascii=False))
